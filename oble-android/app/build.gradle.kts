// Secrets are NEVER committed. An optional build-time default key can come from
// `local.properties` (git-ignored) or the GEMINI_API_KEY environment variable.
// The recommended path is to paste the key into Settings inside the app, where it
// is encrypted with the Android Keystore.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun secret(name: String): String =
    (localProps.getProperty(name) ?: System.getenv(name) ?: "").trim()

